#!/usr/bin/env node
/**
 * Writes `packages/protocol/src/chain/abis.ts` from Foundry's build output.
 *
 *   npm run abis            regenerate (runs `forge build` first)
 *   npm run abis:check      fail if the committed file is stale
 *
 * Every ABI the TypeScript side uses for a contract in this repository comes
 * from here, `as const`, so viem infers argument and return types from the
 * compiled contract rather than from a hand-written mirror that can drift.
 * External contracts (Uniswap's quoter, ERC-20) are not generated.
 *
 * The file is committed, so a TypeScript build never needs Foundry. CI
 * rebuilds the contracts and runs the check.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Contract name in `contracts/out` → export name. */
const CONTRACTS = {
  GameEscrow: 'gameEscrowAbi',
  ProtocolConfig: 'protocolConfigAbi',
  PlayerAvatars: 'playerAvatarsAbi',
  SessionKeyDelegate: 'sessionKeyDelegateAbi',
  SpokeEscrow: 'spokeEscrowAbi',
  LayerZeroMessenger: 'layerZeroMessengerAbi',
  ZapJoin: 'zapJoinAbi',
  FeeRouter: 'feeRouterAbi',
  RewardsDistributor: 'rewardsDistributorAbi',
  StakedLms: 'stakedLmsAbi',
  LmsToken: 'lmsTokenAbi',
  LmsGovernor: 'lmsGovernorAbi',
  // OpenZeppelin's, deployed as is: generated so proposals to it decode.
  TimelockController: 'timelockControllerAbi',
};

const OUT = fileURLToPath(new URL('../contracts/out/', import.meta.url));
const TARGET = fileURLToPath(new URL('../packages/protocol/src/chain/abis.ts', import.meta.url));

const sections = Object.entries(CONTRACTS).map(([contract, name]) => {
  const { abi } = JSON.parse(readFileSync(`${OUT}${contract}.sol/${contract}.json`, 'utf8'));
  // One entry per line, in a stable order, so a diff shows exactly what changed.
  const entries = [...abi].sort(byKindAndName).map((entry) => `  ${JSON.stringify(entry)},`);
  return `/** \`${contract}\`. */\nexport const ${name} = [\n${entries.join('\n')}\n] as const;\n`;
});

const source = `// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit: run \`npm run abis\`.\n\n${sections.join('\n')}`;

if (process.argv.includes('--check')) {
  const current = readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n');
  if (current !== source) {
    console.error('packages/protocol/src/chain/abis.ts is stale: run `npm run abis` and commit the result.');
    process.exit(1);
  }
  console.log('Generated ABIs are up to date.');
} else {
  writeFileSync(TARGET, source);
  console.log(`Wrote ${Object.keys(CONTRACTS).length} ABIs to packages/protocol/src/chain/abis.ts.`);
}

function byKindAndName(a, b) {
  return `${a.type} ${a.name ?? ''}`.localeCompare(`${b.type} ${b.name ?? ''}`) || signature(a).localeCompare(signature(b));
}

/** Tiebreak for overloads: the input types. */
function signature(entry) {
  return (entry.inputs ?? []).map((input) => input.type).join(',');
}

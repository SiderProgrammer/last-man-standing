#!/usr/bin/env node
/**
 * Writes `packages/contracts/src/abis/` from Foundry's build output.
 *
 *   npm run abis            regenerate (runs `forge build` first)
 *   npm run abis:check      fail if the committed files are stale
 *
 * Every ABI the TypeScript side uses for a contract in this repository comes
 * from here, `as const`, so viem infers argument and return types from the
 * compiled contract rather than from a hand-written mirror that can drift.
 * External contracts (Uniswap's quoter, ERC-20) are not generated.
 *
 * The files are committed, so a TypeScript build never needs Foundry. CI
 * rebuilds the contracts and runs the check.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { artifactPath } from './artifacts.mjs';

/** Contract name in `contracts/out` → export name. */
const CONTRACTS = {
  GameEscrow: 'gameEscrowAbi',
  ProtocolConfig: 'protocolConfigAbi',
  PlayerAvatars: 'playerAvatarsAbi',
  SessionKeyDelegate: 'sessionKeyDelegateAbi',
  SpokeRouter: 'spokeRouterAbi',
  BridgeJoinReceiver: 'bridgeJoinReceiverAbi',
  ZapJoin: 'zapJoinAbi',
  FeeRouter: 'feeRouterAbi',
  RewardsDistributor: 'rewardsDistributorAbi',
  RewardVesting: 'rewardVestingAbi',
  StakedLms: 'stakedLmsAbi',
  LmsToken: 'lmsTokenAbi',
  LmsGovernor: 'lmsGovernorAbi',
  // OpenZeppelin's, deployed as is: generated so proposals to it decode.
  TimelockController: 'timelockControllerAbi',
};

const OUT = fileURLToPath(new URL('../contracts/out/', import.meta.url));
const CHAIN = fileURLToPath(new URL('../packages/contracts/src/', import.meta.url));
const HEADER = '// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit: run `npm run abis`.\n';

/**
 * One module per contract, under `abis/`, and `abis.ts`
 * re-exporting them all. A bundler puts each module in exactly one chunk, so
 * one module per ABI is what lets the client's screens loaded on demand
 * (staking, governance) carry their contracts' ABIs with them instead of the
 * whole set riding in the main bundle.
 */
const files = new Map(
  Object.entries(CONTRACTS).map(([contract, name]) => {
    const { abi } = JSON.parse(readFileSync(artifactPath(OUT, contract), 'utf8'));
    // One entry per line, in a stable order, so a diff shows exactly what changed.
    const entries = [...abi].sort(byKindAndName).map((entry) => `  ${JSON.stringify(entry)},`);
    const source = `${HEADER}\n/** \`${contract}\`. */\nexport const ${name} = [\n${entries.join('\n')}\n] as const;\n`;
    return [`abis/${contract}.ts`, source];
  }),
);
const barrel = Object.entries(CONTRACTS).map(([contract, name]) => `export { ${name} } from './abis/${contract}.js';`);
files.set('abis.ts', `${HEADER}\n${barrel.join('\n')}\n`);

if (process.argv.includes('--check')) {
  const stale = [...files].filter(([file, source]) => {
    const path = join(CHAIN, file);
    return !existsSync(path) || readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== source;
  });
  const generated = new Set([...files.keys()].filter((file) => file.startsWith('abis/')));
  const extra = readdirSync(join(CHAIN, 'abis')).filter((file) => !generated.has(`abis/${file}`));
  if (stale.length > 0 || extra.length > 0) {
    const named = [...stale.map(([file]) => file), ...extra.map((file) => `abis/${file} (not generated)`)];
    console.error(`Generated ABIs are stale (${named.join(', ')}): run \`npm run abis\` and commit the result.`);
    process.exit(1);
  }
  console.log('Generated ABIs are up to date.');
} else {
  mkdirSync(join(CHAIN, 'abis'), { recursive: true });
  for (const [file, source] of files) writeFileSync(join(CHAIN, file), source);
  console.log(`Wrote ${Object.keys(CONTRACTS).length} ABIs to packages/contracts/src/abis/.`);
}

function byKindAndName(a, b) {
  return `${a.type} ${a.name ?? ''}`.localeCompare(`${b.type} ${b.name ?? ''}`) || signature(a).localeCompare(signature(b));
}

/** Tiebreak for overloads: the input types. */
function signature(entry) {
  return (entry.inputs ?? []).map((input) => input.type).join(',');
}
